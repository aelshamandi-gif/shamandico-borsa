export function generateCandles(basePrice: number, volatility: number, trend: number, days = 90): Candle[] {
  const candles: Candle[] = [];
  const now = new Date();
  let currentClose = basePrice * (1 - (trend * days * 0.002));

  for (let i = days - 1; i >= 0; i--) {
    const date = new Date(now);
    date.setDate(date.getDate() - i);
    const day = date.getDay();
    if (day === 5 || day === 6) continue;

    const dayChangePct = (Math.random() - 0.48 + trend * 0.05) * volatility;
    const open = Number((currentClose * (1 + (Math.random() - 0.5) * 0.008)).toFixed(2));
    const close = Number((open * (1 + dayChangePct)).toFixed(2));
    const high = Number((Math.max(open, close) * (1 + Math.random() * 0.015)).toFixed(2));
    const low = Number((Math.min(open, close) * (1 - Math.random() * 0.015)).toFixed(2));
    
    const baseVol = Math.floor(1000000 * (15 / (basePrice || 10)));
    const volume = Math.floor(baseVol * (0.6 + Math.random() * 0.8));
    const turnover = Math.floor(volume * close);

    candles.push({
      date: date.toISOString().split('T')[0],
      open,
      high,
      low,
      close,
      volume,
      turnover,
    });

    currentClose = close;
  }

  return candles;
}

export function generateOrderBook(currentPrice: number): { bids: OrderBookEntry[]; asks: OrderBookEntry[] } {
  const bids: OrderBookEntry[] = [];
  const asks: OrderBookEntry[] = [];

  for (let i = 1; i <= 5; i++) {
    const bidPrice = Number((currentPrice * (1 - 0.003 * i)).toFixed(2));
    const askPrice = Number((currentPrice * (1 + 0.003 * i)).toFixed(2));
    const bidQty = Math.floor(5000 + Math.random() * 45000);
    const askQty = Math.floor(5000 + Math.random() * 45000);

    bids.push({
      price: bidPrice,
      quantity: bidQty,
      orders: Math.floor(3 + Math.random() * 15),
    });

    asks.push({
      price: askPrice,
      quantity: askQty,
      orders: Math.floor(3 + Math.random() * 15),
    });
  }

  return { bids, asks };
}

